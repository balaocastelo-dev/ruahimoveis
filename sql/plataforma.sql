-- Herrera HOUSE IA · plataforma de imobiliárias (painel do gestor), 28/10/2026.
-- Cada imobiliária é um schema próprio (ruah, ondemorar, …) com um usuário de banco só dela.
-- O painel do gestor entra com o usuário plataforma_app, que NÃO lê as tabelas das imobiliárias:
-- só a tabela de cadastro (plataforma.*) e as funções abaixo (SECURITY DEFINER), que devolvem números.
-- O usuário plataforma_app é criado à parte (com senha), fora deste arquivo.
CREATE SCHEMA IF NOT EXISTS plataforma;

CREATE TABLE IF NOT EXISTS plataforma.imobiliarias (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE CHECK (slug ~ '^[a-z][a-z0-9_]{2,30}$'),   -- = nome do schema
  nome text NOT NULL,                 -- nome curto (marca)
  empresa text,                       -- nome completo
  contato_nome text, contato_email text, contato_telefone text,
  link text,                          -- endereço do sistema/portal
  dominio text,                       -- domínio próprio (quando houver)
  vercel_projeto text,
  plano text NOT NULL DEFAULT 'essencial',
  mensalidade numeric(12,2) NOT NULL DEFAULT 0,
  comissao_pct numeric(5,2) NOT NULL DEFAULT 20,        -- % da comissão de cada venda que fica com a plataforma
  comissao_venda_pct numeric(5,2) NOT NULL DEFAULT 6,   -- comissão típica da imobiliária sobre o valor do imóvel (para estimar)
  creditos_fisgar_mes integer NOT NULL DEFAULT 0,       -- cota de consultas do Fisgar dada pelo plano
  situacao text NOT NULL DEFAULT 'ativa' CHECK (situacao IN ('ativa','suspensa','implantacao')),
  publicada integer NOT NULL DEFAULT 0,                 -- já tem projeto/link no ar
  db_url_cifrada text,                                  -- conexão do banco da imobiliária (AES, chave do servidor)
  notas text,
  criado_em text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'America/Sao_Paulo', 'YYYY-MM-DD HH24:MI:SS'),
  atualizado_em text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'America/Sao_Paulo', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS plataforma.gestores (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL, email extensions.citext NOT NULL UNIQUE, senha_hash text NOT NULL, ativo integer NOT NULL DEFAULT 1,
  criado_em text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'America/Sao_Paulo', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS plataforma.sessoes (
  token_hash text PRIMARY KEY, gestor_id integer NOT NULL REFERENCES plataforma.gestores(id) ON DELETE CASCADE, expira_em timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS plataforma.tentativas (chave text NOT NULL, em timestamptz NOT NULL DEFAULT now());
CREATE INDEX IF NOT EXISTS ix_plat_tent ON plataforma.tentativas(chave, em);
CREATE TABLE IF NOT EXISTS plataforma.eventos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, gestor_id integer, imobiliaria_id integer, acao text NOT NULL, detalhe text,
  em text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'America/Sao_Paulo', 'YYYY-MM-DD HH24:MI:SS')
);

-- Números de uma imobiliária (só contagens e somas; nada de nomes, telefones ou endereços).
CREATE OR REPLACE FUNCTION plataforma.numeros(p_schema text) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $f$
DECLARE r jsonb; s text := quote_ident(p_schema); mes text := to_char(now() AT TIME ZONE 'America/Sao_Paulo', 'YYYY-MM');
BEGIN
  IF NOT EXISTS (SELECT 1 FROM plataforma.imobiliarias WHERE slug = p_schema) THEN RAISE EXCEPTION 'imobiliária desconhecida'; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = p_schema) THEN RETURN NULL; END IF;
  EXECUTE format($q$
    SELECT jsonb_build_object(
      'usuarios', (SELECT count(*) FROM %1$s.usuarios WHERE ativo = 1),
      'imoveis', (SELECT count(*) FROM %1$s.imoveis),
      'publicados', (SELECT count(*) FROM %1$s.imoveis WHERE status IN ('publicado','off_market')),
      'captacao', (SELECT count(*) FROM %1$s.imoveis WHERE status IN ('captacao','aguardando_autorizacao')),
      'vendidos', (SELECT count(*) FROM %1$s.imoveis WHERE status = 'vendido'),
      'alugados', (SELECT count(*) FROM %1$s.imoveis WHERE status = 'alugado'),
      'vgv_carteira', (SELECT coalesce(sum(valor),0) FROM %1$s.imoveis WHERE status IN ('publicado','off_market','captacao','aguardando_autorizacao')),
      'vendas_mes', (SELECT count(DISTINCT a.detalhe) FROM %1$s.auditoria a WHERE a.acao = 'imovel_status' AND a.detalhe LIKE '%%→ vendido' AND substr(a.em,1,7) = %2$L),
      'valor_vendido_mes', (SELECT coalesce(sum(i.valor),0) FROM %1$s.imoveis i WHERE i.status = 'vendido' AND EXISTS (SELECT 1 FROM %1$s.auditoria a WHERE a.acao = 'imovel_status' AND a.detalhe = i.codigo || ' → vendido' AND substr(a.em,1,7) = %2$L)),
      'valor_vendido_total', (SELECT coalesce(sum(valor),0) FROM %1$s.imoveis WHERE status = 'vendido'),
      'leads', (SELECT count(*) FROM %1$s.leads),
      'leads_30d', (SELECT count(*) FROM %1$s.leads WHERE criado_em >= to_char(now() AT TIME ZONE 'America/Sao_Paulo' - interval '30 days', 'YYYY-MM-DD')),
      'visitas_30d', (SELECT count(*) FROM %1$s.visitas WHERE data_hora >= to_char(now() AT TIME ZONE 'America/Sao_Paulo' - interval '30 days', 'YYYY-MM-DD')),
      'anuncios_base', (SELECT count(*) FROM %1$s.fisguei_anuncios),
      'creditos_mes', (SELECT coalesce(sum(creditos),0) FROM %1$s.fisguei_pedidos WHERE substr(criado_em,1,7) = %2$L),
      'ultima_atividade', (SELECT max(em) FROM %1$s.auditoria),
      'suspensa', (SELECT valor FROM %1$s.config WHERE chave = 'plataforma_suspensa') = '1',
      'social_mes', (SELECT count(*) FROM %1$s.social_posts WHERE status IN ('publicado','parcial') AND substr(coalesce(publicado_em, agendado_para),1,7) = %2$L),
      'social_contas', (SELECT count(*) FROM %1$s.social_contas WHERE ativo = 1),
      'tamanho_mb', (SELECT round(sum(pg_total_relation_size(c.oid)) / 1048576.0, 1) FROM pg_class c WHERE c.relnamespace = %3$L::regnamespace AND c.relkind = 'r')
    )$q$, s, mes, p_schema) INTO r;
  RETURN r;
END $f$;

-- Suspender / reativar: grava na configuração da própria imobiliária (o sistema dela lê e mostra "conta suspensa").
CREATE OR REPLACE FUNCTION plataforma.suspender(p_schema text, p_suspensa boolean) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $f$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM plataforma.imobiliarias WHERE slug = p_schema) THEN RAISE EXCEPTION 'imobiliária desconhecida'; END IF;
  EXECUTE format('INSERT INTO %I.config(chave, valor) VALUES (''plataforma_suspensa'', %L) ON CONFLICT (chave) DO UPDATE SET valor = excluded.valor',
    p_schema, CASE WHEN p_suspensa THEN '1' ELSE '0' END);
  UPDATE plataforma.imobiliarias SET situacao = CASE WHEN p_suspensa THEN 'suspensa' ELSE 'ativa' END,
    atualizado_em = to_char(now() AT TIME ZONE 'America/Sao_Paulo', 'YYYY-MM-DD HH24:MI:SS') WHERE slug = p_schema;
END $f$;

-- Nova imobiliária: schema com a mesma estrutura da RUAH (vazio), base comum por views, usuário de banco próprio
-- e o administrador. A senha do banco e o hash da senha do admin vêm do servidor (nunca ficam neste arquivo).
CREATE OR REPLACE FUNCTION plataforma.criar_imobiliaria(p_slug text, p_db_senha text, p_admin_nome text, p_admin_email text, p_admin_hash text) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $f$
DECLARE t record; f record; compart text[] := ARRAY['condominios','predios3d','mapa3d','pois','fachadas']; papel text := p_slug || '_app';
BEGIN
  IF p_slug !~ '^[a-z][a-z0-9_]{2,30}$' OR p_slug IN ('ruah','plataforma','public','extensions','auth','storage','realtime','pg_catalog','information_schema') THEN
    RAISE EXCEPTION 'nome técnico inválido'; END IF;
  IF NOT EXISTS (SELECT 1 FROM plataforma.imobiliarias WHERE slug = p_slug) THEN RAISE EXCEPTION 'cadastre a imobiliária antes'; END IF;
  IF EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = p_slug) THEN RAISE EXCEPTION 'esse banco já existe'; END IF;
  EXECUTE format('CREATE SCHEMA %I', p_slug);
  EXECUTE format($q$CREATE FUNCTION %I.agora() RETURNS text LANGUAGE sql STABLE AS 'SELECT to_char(now() AT TIME ZONE ''America/Sao_Paulo'', ''YYYY-MM-DD HH24:MI:SS'')'$q$, p_slug);
  FOR t IN SELECT c.relname FROM pg_class c JOIN pg_namespace s ON s.oid = c.relnamespace
           WHERE s.nspname = 'ruah' AND c.relkind = 'r' AND c.relname <> ALL(compart) AND c.relname NOT LIKE 'bkp_%' LOOP
    EXECUTE format('CREATE TABLE %I.%I (LIKE ruah.%I INCLUDING ALL)', p_slug, t.relname, t.relname);
  END LOOP;
  FOR t IN SELECT unnest(compart) relname LOOP
    EXECUTE format('CREATE VIEW %I.%I AS SELECT * FROM ruah.%I', p_slug, t.relname, t.relname);
  END LOOP;
  FOR f IN SELECT conname, conrelid::regclass::text rel, pg_get_constraintdef(oid) def FROM pg_constraint
           WHERE contype = 'f' AND connamespace = 'ruah'::regnamespace AND confrelid::regclass::text !~ '(condominios|predios3d|mapa3d|pois|fachadas)$'
             AND conrelid::regclass::text !~ 'bkp_' LOOP
    EXECUTE format('ALTER TABLE %I.%I ADD CONSTRAINT %I %s', p_slug, split_part(f.rel, '.', 2), f.conname, replace(f.def, 'ruah.', quote_ident(p_slug) || '.'));
  END LOOP;
  FOR f IN SELECT table_name, column_name, column_default FROM information_schema.columns WHERE table_schema = p_slug AND column_default LIKE '%ruah.agora()%' LOOP
    EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN %I SET DEFAULT %s', p_slug, f.table_name, f.column_name, replace(f.column_default, 'ruah.agora()', quote_ident(p_slug) || '.agora()'));
  END LOOP;
  EXECUTE format('INSERT INTO %I.bairros SELECT * FROM ruah.bairros', p_slug);
  EXECUTE format('INSERT INTO %I.bairro_commons SELECT * FROM ruah.bairro_commons', p_slug);
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = papel) THEN
    EXECUTE format('CREATE ROLE %I LOGIN PASSWORD %L', papel, p_db_senha);
  END IF;
  EXECUTE format('ALTER ROLE %I SET search_path = %I, extensions', papel, p_slug);
  EXECUTE format('ALTER ROLE %I SET statement_timeout = %L', papel, '30s');
  EXECUTE format('GRANT USAGE ON SCHEMA %I TO %I', p_slug, papel);
  EXECUTE format('GRANT USAGE ON SCHEMA extensions TO %I', papel);
  EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA %I TO %I', p_slug, papel);
  EXECUTE format('GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA %I TO %I', p_slug, papel);
  EXECUTE format('GRANT EXECUTE ON FUNCTION %I.agora() TO %I', p_slug, papel);
  -- Redes e publicações (sql/social.sql): a cadência vem do plano (plataforma.meu_plano) e o ciclo já tem o token desta imobiliária
  EXECUTE format('GRANT USAGE ON SCHEMA plataforma TO %I', papel);
  EXECUTE format('GRANT EXECUTE ON FUNCTION plataforma.meu_plano() TO %I', papel);
  EXECUTE format('INSERT INTO %I.config(chave, valor) VALUES (''social_ciclo_token'', encode(extensions.gen_random_bytes(24), ''hex'')) ON CONFLICT (chave) DO NOTHING', p_slug);
  EXECUTE format('INSERT INTO %I.usuarios(nome, email, perfil, senha_hash) VALUES (%L, %L, ''adm'', %L)', p_slug, p_admin_nome, p_admin_email, p_admin_hash);
  UPDATE plataforma.imobiliarias SET situacao = 'implantacao' WHERE slug = p_slug;
  PERFORM plataforma.compartilhar_base(p_slug); -- já começa vendo todos os anúncios da base (sql/plataforma-base-comum.sql)
END $f$;

REVOKE ALL ON FUNCTION plataforma.numeros(text), plataforma.suspender(text, boolean), plataforma.criar_imobiliaria(text, text, text, text, text) FROM PUBLIC;
