-- Etapa 1: aplicar DEPOIS de escritorio.sql, uma vez em cada schema.
-- Trocar ruah e ruah_app por ondemorar/ondemorar_app, cademeuap/cademeuap_app,
-- casaprado/casaprado_app ou lumen/lumen_app. Reexecutável.
BEGIN;
SET LOCAL search_path = ruah, extensions;
CREATE TABLE IF NOT EXISTS chat_conversas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo text NOT NULL CHECK (tipo IN ('direta','sala')), titulo text,
  criado_por integer NOT NULL REFERENCES usuarios(id), par text UNIQUE,
  criado_em text NOT NULL DEFAULT ruah.agora(), ultima_em text, ultima_texto text,
  ultima_id integer NOT NULL DEFAULT 0
);
-- NULL não pode compor uma PK no Postgres; os índices garantem a identidade por pessoa/robô.
CREATE TABLE IF NOT EXISTS chat_participantes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversa_id integer NOT NULL REFERENCES chat_conversas(id) ON DELETE CASCADE,
  usuario_id integer REFERENCES usuarios(id), agente text,
  lido_ate integer NOT NULL DEFAULT 0, silenciado integer NOT NULL DEFAULT 0 CHECK (silenciado IN (0,1)),
  CHECK ((usuario_id IS NOT NULL AND agente IS NULL) OR (usuario_id IS NULL AND agente IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_cp_usuario ON chat_participantes(conversa_id,usuario_id) WHERE usuario_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_cp_agente ON chat_participantes(conversa_id,agente) WHERE agente IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_cp_usuario ON chat_participantes(usuario_id,conversa_id);
CREATE TABLE IF NOT EXISTS chat_mensagens (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversa_id integer NOT NULL REFERENCES chat_conversas(id) ON DELETE CASCADE,
  de_usuario integer REFERENCES usuarios(id), de_agente text,
  tipo text NOT NULL DEFAULT 'texto' CHECK (tipo IN ('texto','audio','arquivo','sistema')), texto text,
  arquivo_id integer REFERENCES arquivos(id), agente_mensagem_id integer UNIQUE,
  criado_em text NOT NULL DEFAULT ruah.agora(),
  CHECK ((de_usuario IS NOT NULL AND de_agente IS NULL) OR (de_usuario IS NULL AND de_agente IS NOT NULL) OR (tipo='sistema' AND de_usuario IS NULL AND de_agente IS NULL))
);
CREATE INDEX IF NOT EXISTS ix_cm_conversa ON chat_mensagens(conversa_id,id);
CREATE INDEX IF NOT EXISTS ix_cm_criado ON chat_mensagens(criado_em);
CREATE OR REPLACE FUNCTION ruah.chat_atualiza_ultima() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE ruah.chat_conversas SET ultima_id=NEW.id, ultima_em=NEW.criado_em, ultima_texto=substr(NEW.texto,1,240)
    WHERE id=NEW.conversa_id AND ultima_id<NEW.id;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS chat_ultima ON chat_mensagens;
CREATE TRIGGER chat_ultima AFTER INSERT ON chat_mensagens FOR EACH ROW EXECUTE FUNCTION ruah.chat_atualiza_ultima();
-- Só o backend autenticado acessa estas tabelas. Sem anon key / Supabase Realtime.
ALTER TABLE chat_conversas ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat_participantes ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat_mensagens ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON chat_conversas, chat_participantes, chat_mensagens FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON chat_conversas, chat_participantes, chat_mensagens TO ruah_app;
DROP POLICY IF EXISTS chat_backend ON chat_conversas;
CREATE POLICY chat_backend ON chat_conversas TO ruah_app USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS chat_backend ON chat_participantes;
CREATE POLICY chat_backend ON chat_participantes TO ruah_app USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS chat_backend ON chat_mensagens;
CREATE POLICY chat_backend ON chat_mensagens TO ruah_app USING (true) WITH CHECK (true);
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA ruah TO ruah_app;
COMMIT;
