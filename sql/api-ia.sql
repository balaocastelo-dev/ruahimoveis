-- API de controle por IA (30/10/2026): chaves de API e registro de uso.
-- Aplicar no Supabase uma vez. Cria as tabelas na RUAH (o molde que plataforma.criar_imobiliaria copia)
-- e em todas as imobiliárias que já existem, com o usuário de banco de cada uma.
DO $$
DECLARE s record; sch text;
BEGIN
  FOR s IN SELECT 'ruah' AS slug UNION SELECT i.slug FROM plataforma.imobiliarias i JOIN pg_namespace n ON n.nspname = i.slug LOOP
    sch := s.slug;
    CONTINUE WHEN NOT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = sch);
    EXECUTE format($q$CREATE TABLE IF NOT EXISTS %1$I.api_chaves (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      nome text NOT NULL, prefixo text NOT NULL UNIQUE, chave_hash text NOT NULL,
      usuario_id integer REFERENCES %1$I.usuarios(id) ON DELETE CASCADE,
      escopos text NOT NULL DEFAULT '*', somente_leitura integer NOT NULL DEFAULT 0,
      limite_min integer NOT NULL DEFAULT 300, ips text, expira_em text, ativo integer NOT NULL DEFAULT 1,
      usos integer NOT NULL DEFAULT 0, ultimo_uso text, ultimo_ip text,
      criada_por integer REFERENCES %1$I.usuarios(id) ON DELETE SET NULL,
      criada_em text NOT NULL DEFAULT %1$I.agora())$q$, sch);
    EXECUTE format($q$CREATE TABLE IF NOT EXISTS %1$I.api_log (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      chave_id integer REFERENCES %1$I.api_chaves(id) ON DELETE CASCADE,
      metodo text NOT NULL, caminho text NOT NULL, status integer, ms integer, ip text, acao text, erro text,
      em text NOT NULL DEFAULT %1$I.agora())$q$, sch);
    EXECUTE format('CREATE INDEX IF NOT EXISTS ix_apilog_chave ON %I.api_log(chave_id, id)', sch);
    EXECUTE format('CREATE INDEX IF NOT EXISTS ix_apilog_em ON %I.api_log(em)', sch);
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = sch || '_app') THEN
      EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %1$I.api_chaves, %1$I.api_log TO %2$I', sch, sch || '_app');
      EXECUTE format('GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA %I TO %I', sch, sch || '_app');
    END IF;
  END LOOP;
END $$;
