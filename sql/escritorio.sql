-- Escritório virtual (27/10/2026): aplicar no Supabase (schema ruah).
SET search_path = ruah, extensions;

ALTER TABLE leads ADD COLUMN IF NOT EXISTS agente text;

CREATE TABLE IF NOT EXISTS agente_mensagens (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agente text NOT NULL, linha text, telefone text NOT NULL, nome text,
  direcao text NOT NULL CHECK (direcao IN ('entrada','saida','nota')), texto text NOT NULL, status text,
  lead_id integer REFERENCES leads(id) ON DELETE SET NULL,
  pessoa_id integer REFERENCES fisguei_pessoas(id) ON DELETE SET NULL,
  wa_id text, autor text, processada integer NOT NULL DEFAULT 0, motivo text,
  criado_em text NOT NULL DEFAULT ruah.agora(), enviado_em text
);
CREATE INDEX IF NOT EXISTS ix_am_agente ON agente_mensagens(agente, telefone);
CREATE INDEX IF NOT EXISTS ix_am_proc ON agente_mensagens(processada, direcao);
CREATE INDEX IF NOT EXISTS ix_am_status ON agente_mensagens(direcao, status);
CREATE INDEX IF NOT EXISTS ix_am_wa ON agente_mensagens(wa_id);

CREATE TABLE IF NOT EXISTS agente_eventos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agente text NOT NULL, tipo text NOT NULL, texto text, ref text, chave text UNIQUE,
  criado_em text NOT NULL DEFAULT ruah.agora()
);
CREATE INDEX IF NOT EXISTS ix_ae_agente ON agente_eventos(agente, id);

CREATE TABLE IF NOT EXISTS agente_afazeres (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  corretor_id integer REFERENCES usuarios(id) ON DELETE CASCADE, texto text NOT NULL, quando text,
  lead_id integer REFERENCES leads(id) ON DELETE SET NULL, imovel_id integer REFERENCES imoveis(id) ON DELETE SET NULL, origem text,
  feito integer NOT NULL DEFAULT 0, feito_em text, lembrado_em text, criado_em text NOT NULL DEFAULT ruah.agora()
);
CREATE INDEX IF NOT EXISTS ix_af_corretor ON agente_afazeres(corretor_id, feito);

CREATE TABLE IF NOT EXISTS agente_midias (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agente text NOT NULL, telefone text,
  pessoa_id integer REFERENCES fisguei_pessoas(id) ON DELETE SET NULL,
  anuncio_id integer REFERENCES fisguei_anuncios(id) ON DELETE SET NULL,
  oportunidade_id integer REFERENCES oportunidades(id) ON DELETE SET NULL,
  lead_id integer REFERENCES leads(id) ON DELETE SET NULL,
  mime text, nome text, tamanho integer, legenda text, dados bytea NOT NULL,
  imovel_arquivo_id integer, criado_em text NOT NULL DEFAULT ruah.agora()
);

GRANT SELECT, INSERT, UPDATE, DELETE ON ruah.agente_mensagens, ruah.agente_eventos, ruah.agente_afazeres, ruah.agente_midias TO ruah_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA ruah TO ruah_app;
