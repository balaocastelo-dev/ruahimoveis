-- Redes e publicações (28/10/2026): posts agendados no Instagram, Facebook e Google Meu Negócio.
-- Aplicar no Supabase uma vez. Cria as tabelas na RUAH (o molde: plataforma.criar_imobiliaria copia
-- para as próximas) e em todas as imobiliárias que já existem, com o usuário de banco de cada uma.
-- Também: plataforma.meu_plano() (o plano de quem pergunta, para a cadência), o ciclo das publicações
-- (pg_cron a cada 10 minutos chama <link>/social-ciclo de cada imobiliária ativa com o token dela)
-- e os números de redes no painel do gestor.

DO $$
DECLARE s record; sch text;
BEGIN
  FOR s IN SELECT 'ruah' AS slug UNION SELECT i.slug FROM plataforma.imobiliarias i JOIN pg_namespace n ON n.nspname = i.slug LOOP
    sch := s.slug;
    CONTINUE WHEN NOT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = sch);
    EXECUTE format($q$CREATE TABLE IF NOT EXISTS %1$I.social_posts (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, chave text NOT NULL UNIQUE, tipo text NOT NULL, ref text, titulo text NOT NULL,
      legenda text, hashtags text, link text, slides text NOT NULL DEFAULT '[]', agendado_para text NOT NULL,
      status text NOT NULL DEFAULT 'agendado', redes text NOT NULL DEFAULT '[]', resultado text NOT NULL DEFAULT '{}',
      origem text NOT NULL DEFAULT 'auto', editado integer NOT NULL DEFAULT 0, versao integer NOT NULL DEFAULT 1, motivo text,
      aprovado_por integer REFERENCES %1$I.usuarios(id) ON DELETE SET NULL, aprovado_em text, publicado_em text,
      criado_em text NOT NULL DEFAULT %1$I.agora(), atualizado_em text NOT NULL DEFAULT %1$I.agora())$q$, sch);
    EXECUTE format('CREATE INDEX IF NOT EXISTS ix_sp_agenda ON %I.social_posts(agendado_para)', sch);
    EXECUTE format('CREATE INDEX IF NOT EXISTS ix_sp_status ON %I.social_posts(status, agendado_para)', sch);
    EXECUTE format('CREATE INDEX IF NOT EXISTS ix_sp_ref ON %I.social_posts(tipo, ref)', sch);
    EXECUTE format($q$CREATE TABLE IF NOT EXISTS %1$I.social_contas (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, rede text NOT NULL, conta_id text NOT NULL, nome text, usuario text, token text, refresh text,
      expira_em text, dados text, ativo integer NOT NULL DEFAULT 1, ultimo_erro text,
      conectado_por integer REFERENCES %1$I.usuarios(id) ON DELETE SET NULL, conectado_em text NOT NULL DEFAULT %1$I.agora(),
      UNIQUE (rede, conta_id))$q$, sch);
    EXECUTE format($q$CREATE TABLE IF NOT EXISTS %1$I.social_cliques (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, post_id integer REFERENCES %1$I.social_posts(id) ON DELETE CASCADE, rede text,
      em text NOT NULL DEFAULT %1$I.agora())$q$, sch);
    EXECUTE format('CREATE INDEX IF NOT EXISTS ix_sc_post ON %I.social_cliques(post_id)', sch);
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = sch || '_app') THEN
      EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %1$I.social_posts, %1$I.social_contas, %1$I.social_cliques TO %2$I', sch, sch || '_app');
      EXECUTE format('GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA %I TO %I', sch, sch || '_app');
    END IF;
  END LOOP;
END $$;

-- O plano de quem pergunta (o usuário de banco <slug>_app só enxerga o próprio plano).
CREATE OR REPLACE FUNCTION plataforma.meu_plano() RETURNS text
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $f$
  SELECT plano FROM plataforma.imobiliarias WHERE slug || '_app' = session_user LIMIT 1
$f$;
REVOKE ALL ON FUNCTION plataforma.meu_plano() FROM PUBLIC;
DO $$
DECLARE r record;
BEGIN
  FOR r IN SELECT rolname FROM pg_roles WHERE rolname LIKE '%\_app' AND rolname <> 'plataforma_app' LOOP
    EXECUTE format('GRANT USAGE ON SCHEMA plataforma TO %I', r.rolname);
    EXECUTE format('GRANT EXECUTE ON FUNCTION plataforma.meu_plano() TO %I', r.rolname);
  END LOOP;
END $$;

-- O ciclo: chama /social-ciclo de cada imobiliária ativa e publicada, com o token guardado no banco dela
-- (o token nasce quando alguém abre a tela Redes e publicações; sem token, a imobiliária é pulada).
CREATE OR REPLACE FUNCTION plataforma.social_ciclo() RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $f$
DECLARE i record; tk text; n integer := 0;
BEGIN
  FOR i IN SELECT x.slug, x.link FROM plataforma.imobiliarias x JOIN pg_namespace ns ON ns.nspname = x.slug
           WHERE x.situacao = 'ativa' AND x.publicada = 1 AND x.link ~ '^https://' LOOP
    BEGIN
      EXECUTE format('SELECT valor FROM %I.config WHERE chave = ''social_ciclo_token''', i.slug) INTO tk;
    EXCEPTION WHEN OTHERS THEN tk := NULL; END;
    CONTINUE WHEN tk IS NULL;
    PERFORM net.http_post(url := rtrim(i.link, '/') || '/social-ciclo',
      headers := jsonb_build_object('Content-Type', 'application/json', 'x-social-ciclo', tk), body := '{}'::jsonb, timeout_milliseconds := 60000);
    n := n + 1;
  END LOOP;
  RETURN n;
END $f$;
REVOKE ALL ON FUNCTION plataforma.social_ciclo() FROM PUBLIC;
SELECT cron.unschedule(jobid) FROM cron.job WHERE jobname = 'plataforma-social-ciclo';
SELECT cron.schedule('plataforma-social-ciclo', '*/10 * * * *', $c$ SELECT plataforma.social_ciclo() $c$);

-- Números do painel do gestor, agora com as redes (publicados no mês e contas conectadas).
CREATE OR REPLACE FUNCTION plataforma.numeros(p_schema text) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $f$
DECLARE r jsonb; s text := quote_ident(p_schema); mes text := to_char(now() AT TIME ZONE 'America/Sao_Paulo', 'YYYY-MM');
BEGIN
  IF NOT EXISTS (SELECT 1 FROM plataforma.imobiliarias WHERE slug = p_schema) THEN RAISE EXCEPTION 'imobiliária desconhecida'; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = p_schema) THEN RETURN NULL; END IF;
  EXECUTE format($q$
    SELECT jsonb_build_object(
      'usuarios', (SELECT count(*) FROM %1$s.usuarios WHERE ativo = 1),
      'imoveis', (SELECT count(*) FROM %1$s.imoveis),
      'publicados', (SELECT count(*) FROM %1$s.imoveis WHERE status IN ('publicado','off_market')),
      'captacao', (SELECT count(*) FROM %1$s.imoveis WHERE status IN ('captacao','aguardando_autorizacao')),
      'vendidos', (SELECT count(*) FROM %1$s.imoveis WHERE status = 'vendido'),
      'alugados', (SELECT count(*) FROM %1$s.imoveis WHERE status = 'alugado'),
      'vgv_carteira', (SELECT coalesce(sum(valor),0) FROM %1$s.imoveis WHERE status IN ('publicado','off_market','captacao','aguardando_autorizacao')),
      'vendas_mes', (SELECT count(DISTINCT a.detalhe) FROM %1$s.auditoria a WHERE a.acao = 'imovel_status' AND a.detalhe LIKE '%%→ vendido' AND substr(a.em,1,7) = %2$L),
      'valor_vendido_mes', (SELECT coalesce(sum(i.valor),0) FROM %1$s.imoveis i WHERE i.status = 'vendido' AND EXISTS (SELECT 1 FROM %1$s.auditoria a WHERE a.acao = 'imovel_status' AND a.detalhe = i.codigo || ' → vendido' AND substr(a.em,1,7) = %2$L)),
      'valor_vendido_total', (SELECT coalesce(sum(valor),0) FROM %1$s.imoveis WHERE status = 'vendido'),
      'leads', (SELECT count(*) FROM %1$s.leads),
      'leads_30d', (SELECT count(*) FROM %1$s.leads WHERE criado_em >= to_char(now() AT TIME ZONE 'America/Sao_Paulo' - interval '30 days', 'YYYY-MM-DD')),
      'visitas_30d', (SELECT count(*) FROM %1$s.visitas WHERE data_hora >= to_char(now() AT TIME ZONE 'America/Sao_Paulo' - interval '30 days', 'YYYY-MM-DD')),
      'anuncios_base', (SELECT count(*) FROM %1$s.fisguei_anuncios),
      'creditos_mes', (SELECT coalesce(sum(creditos),0) FROM %1$s.fisguei_pedidos WHERE substr(criado_em,1,7) = %2$L),
      'ultima_atividade', (SELECT max(em) FROM %1$s.auditoria),
      'suspensa', (SELECT valor FROM %1$s.config WHERE chave = 'plataforma_suspensa') = '1',
      'social_mes', (SELECT count(*) FROM %1$s.social_posts WHERE status IN ('publicado','parcial') AND substr(coalesce(publicado_em, agendado_para),1,7) = %2$L),
      'social_contas', (SELECT count(*) FROM %1$s.social_contas WHERE ativo = 1),
      'tamanho_mb', (SELECT round(sum(pg_total_relation_size(c.oid)) / 1048576.0, 1) FROM pg_class c WHERE c.relnamespace = %3$L::regnamespace AND c.relkind = 'r')
    )$q$, s, mes, p_schema) INTO r;
  RETURN r;
END $f$;
