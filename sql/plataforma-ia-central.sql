-- Cérebro central da plataforma (29/10/2026): uma única chave do Gemini, da plataforma, que todas as
-- imobiliárias usam de graça. Aplicar UMA VEZ no schema plataforma.
--
-- A chave em si fica em plataforma.config (chaves 'ia_central' e 'ia_central_modelo'), como os outros
-- segredos de lá (tokens de ciclo). Quem a lê é o usuário plataforma_app, que toda imobiliária já usa
-- pelo PLATAFORMA_DATABASE_URL. A chave nunca sai numa rota: a tela só vê os 4 últimos dígitos.
BEGIN;
SET LOCAL search_path = plataforma, extensions;

-- O que cada imobiliária consumiu do cérebro central (uma linha por imobiliária, dia e modelo).
CREATE TABLE IF NOT EXISTS ia_uso (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  imobiliaria text NOT NULL,
  dia date NOT NULL DEFAULT (now() AT TIME ZONE 'America/Sao_Paulo')::date,
  modelo text NOT NULL DEFAULT 'desconhecido',
  chamadas integer NOT NULL DEFAULT 0,
  tokens_entrada bigint NOT NULL DEFAULT 0,
  tokens_saida bigint NOT NULL DEFAULT 0,
  erros integer NOT NULL DEFAULT 0,
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  UNIQUE (imobiliaria, dia, modelo)
);
CREATE INDEX IF NOT EXISTS ix_ia_uso_dia ON ia_uso(dia DESC, imobiliaria);

ALTER TABLE ia_uso ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ia_uso FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON ia_uso TO plataforma_app;
DROP POLICY IF EXISTS ia_uso_backend ON ia_uso;
CREATE POLICY ia_uso_backend ON ia_uso TO plataforma_app USING (true) WITH CHECK (true);
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA plataforma TO plataforma_app;

-- plataforma_app precisa ler as duas chaves novas de config (já tem acesso à tabela).
COMMIT;
