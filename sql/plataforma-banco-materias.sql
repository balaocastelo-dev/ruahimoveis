-- Banco de matérias do blog (Herrera HOUSE IA, 28/10/2026).
--
-- Uma fábrica central escreve matérias (Claude) e faz as capas (RTX 4090); elas ficam em
-- plataforma.materias. Todo dia a entrega distribui as prontas entre as imobiliárias ativas,
-- conforme o plano (Essencial 1, Profissional 2, Rede/Fundador 3 por dia; materias_dia troca).
--
-- Regras que o próprio banco garante:
--   * uma matéria vai para UMA imobiliária só (entregue_a é preenchido uma vez, com trava de linha);
--   * a mesma imobiliária não recebe dois textos do mesmo tema em 90 dias;
--   * notícia vencida (valido_ate) não é entregue;
--   * rodar a entrega de novo no mesmo dia não duplica nada (um horário = uma matéria).
-- O texto do banco usa {{cliente}} no lugar do nome; a entrega troca pelo nome da imobiliária.

CREATE TABLE IF NOT EXISTS plataforma.materias (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  tipo text NOT NULL CHECK (tipo IN ('principal','noticia','dica')),
  categoria text NOT NULL,
  titulo text NOT NULL,
  tema text NOT NULL,                         -- assunto em poucas palavras, normalizado (sem acento, minúsculas)
  conteudo jsonb NOT NULL,                    -- o artigo inteiro (mesmo formato do blog), com {{cliente}}
  criada_em timestamptz NOT NULL DEFAULT now(),
  valido_ate timestamptz,                     -- notícia: até quando faz sentido publicar
  entregue_a text REFERENCES plataforma.imobiliarias(slug) ON UPDATE CASCADE,
  entregue_em timestamptz,
  publicar_em timestamptz,                    -- horário em que aparece no blog da imobiliária
  CHECK ((entregue_a IS NULL) = (entregue_em IS NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_materias_tema ON plataforma.materias (tema);
CREATE INDEX IF NOT EXISTS ix_materias_livres ON plataforma.materias (tipo, criada_em) WHERE entregue_a IS NULL;
CREATE INDEX IF NOT EXISTS ix_materias_entregues ON plataforma.materias (entregue_a, publicar_em);
CREATE UNIQUE INDEX IF NOT EXISTS ux_materias_horario ON plataforma.materias (entregue_a, publicar_em) WHERE entregue_a IS NOT NULL;

ALTER TABLE plataforma.imobiliarias ADD COLUMN IF NOT EXISTS materias_dia integer CHECK (materias_dia BETWEEN 0 AND 3);

CREATE TABLE IF NOT EXISTS plataforma.config (chave text PRIMARY KEY, valor text);

GRANT SELECT, INSERT, UPDATE ON plataforma.materias TO plataforma_app;
GRANT SELECT ON plataforma.config TO plataforma_app;

-- Cada imobiliária guarda as matérias que recebeu (o blog dela lê daqui). A RUAH é o molde:
-- criar_imobiliaria copia a estrutura para as próximas.
DO $$
DECLARE s record;
BEGIN
  FOR s IN SELECT i.slug FROM plataforma.imobiliarias i JOIN pg_namespace n ON n.nspname = i.slug LOOP
    EXECUTE format($q$CREATE TABLE IF NOT EXISTS %I.blog_materias (
      slug text PRIMARY KEY, titulo text NOT NULL, categoria text NOT NULL, publicado_em text NOT NULL,
      conteudo text NOT NULL, recebida_em text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'America/Sao_Paulo', 'YYYY-MM-DD HH24:MI:SS'))$q$, s.slug);
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = s.slug || '_app') THEN
      EXECUTE format('GRANT SELECT ON %I.blog_materias TO %I', s.slug, s.slug || '_app');
    END IF;
  END LOOP;
END $$;

-- Quantas por dia, pelo plano.
CREATE OR REPLACE FUNCTION plataforma.materias_por_dia(p_plano text, p_fixo integer) RETURNS integer
LANGUAGE sql IMMUTABLE AS $f$
  SELECT least(3, greatest(0, coalesce(p_fixo, CASE lower(coalesce(p_plano, '')) WHEN 'rede' THEN 3 WHEN 'fundador' THEN 3 WHEN 'profissional' THEN 2 ELSE 1 END)))
$f$;

-- A entrega de um dia (padrão: hoje em Campinas). Pode rodar quantas vezes quiser.
CREATE OR REPLACE FUNCTION plataforma.entregar_materias(p_dia date DEFAULT NULL) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $f$
DECLARE
  dia date := coalesce(p_dia, (now() AT TIME ZONE 'America/Sao_Paulo')::date);
  im record; m record; n integer; i integer; tipos text[]; horas text[];
  quando timestamptz; iso text; nome_json text; corpo text; feitas jsonb := '[]'::jsonb; faltou jsonb := '[]'::jsonb;
BEGIN
  FOR im IN SELECT x.slug, x.nome, x.plano, x.materias_dia FROM plataforma.imobiliarias x
            JOIN pg_namespace ns ON ns.nspname = x.slug
            WHERE x.situacao = 'ativa' ORDER BY x.id LOOP
    n := plataforma.materias_por_dia(im.plano, im.materias_dia);
    CONTINUE WHEN n = 0;
    IF n = 3 THEN tipos := ARRAY['principal','noticia','dica']; horas := ARRAY['06:00','12:00','18:00'];
    ELSIF n = 2 THEN tipos := ARRAY['principal','dica']; horas := ARRAY['06:00','18:00'];
    ELSE tipos := ARRAY[(ARRAY['principal','dica','noticia'])[1 + ((dia - DATE '2026-01-01') % 3)]]; horas := ARRAY['06:00'];
    END IF;
    nome_json := substr(to_json(im.nome)::text, 2, length(to_json(im.nome)::text) - 2);
    FOR i IN 1..n LOOP
      quando := ((dia::text || ' ' || horas[i])::timestamp) AT TIME ZONE 'America/Sao_Paulo';
      CONTINUE WHEN EXISTS (SELECT 1 FROM plataforma.materias WHERE entregue_a = im.slug AND publicar_em = quando);
      SELECT x.* INTO m FROM plataforma.materias x
       WHERE x.entregue_a IS NULL
         AND (x.valido_ate IS NULL OR x.valido_ate > quando)
         AND NOT EXISTS (SELECT 1 FROM plataforma.materias y WHERE y.entregue_a = im.slug AND y.tema = x.tema AND y.entregue_em > now() - interval '90 days')
       ORDER BY (x.tipo = tipos[i]) DESC,
                CASE WHEN x.tipo = 'noticia' THEN -extract(epoch FROM x.criada_em) ELSE extract(epoch FROM x.criada_em) END
       LIMIT 1 FOR UPDATE SKIP LOCKED;
      IF NOT FOUND THEN faltou := faltou || jsonb_build_object('imobiliaria', im.slug, 'horario', horas[i]); CONTINUE; END IF;
      iso := to_char(quando AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS".000Z"');
      corpo := jsonb_set(replace(m.conteudo::text, '{{cliente}}', nome_json)::jsonb, '{publicadoEm}', to_jsonb(iso))::text;
      EXECUTE format('INSERT INTO %I.blog_materias(slug, titulo, categoria, publicado_em, conteudo) VALUES ($1, $2, $3, $4, $5) ON CONFLICT (slug) DO NOTHING', im.slug)
        USING m.slug, replace(m.titulo, '{{cliente}}', im.nome), m.categoria, iso, corpo;
      UPDATE plataforma.materias SET entregue_a = im.slug, entregue_em = now(), publicar_em = quando WHERE id = m.id;
      feitas := feitas || jsonb_build_object('imobiliaria', im.slug, 'slug', m.slug, 'tipo', m.tipo, 'quando', iso);
    END LOOP;
  END LOOP;
  IF jsonb_array_length(feitas) > 0 OR jsonb_array_length(faltou) > 0 THEN
    INSERT INTO plataforma.eventos(acao, detalhe) VALUES ('banco_materias',
      format('%s entregue(s) para %s; %s horário(s) sem matéria no banco', jsonb_array_length(feitas), dia, jsonb_array_length(faltou)));
  END IF;
  RETURN jsonb_build_object('dia', dia, 'entregues', feitas, 'faltaram', faltou);
END $f$;

-- Situação do estoque (para o painel do gestor e para a rotina que escreve).
CREATE OR REPLACE FUNCTION plataforma.banco_situacao() RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $f$
  WITH livres AS (SELECT tipo, count(*) n FROM plataforma.materias WHERE entregue_a IS NULL AND (valido_ate IS NULL OR valido_ate > now()) GROUP BY tipo),
  consumo AS (SELECT coalesce(sum(plataforma.materias_por_dia(plano, materias_dia)), 0) n FROM plataforma.imobiliarias WHERE situacao = 'ativa')
  SELECT jsonb_build_object(
    'livres', (SELECT coalesce(jsonb_object_agg(tipo, n), '{}'::jsonb) FROM livres),
    'total_livres', (SELECT coalesce(sum(n), 0) FROM livres),
    'vencidas', (SELECT count(*) FROM plataforma.materias WHERE entregue_a IS NULL AND valido_ate <= now()),
    'entregues', (SELECT count(*) FROM plataforma.materias WHERE entregue_a IS NOT NULL),
    'consumo_dia', (SELECT n FROM consumo),
    'dias_de_estoque', (SELECT CASE WHEN c.n = 0 THEN NULL ELSE round((SELECT coalesce(sum(n), 0) FROM livres)::numeric / c.n, 1) END FROM consumo c),
    'por_imobiliaria', (SELECT coalesce(jsonb_agg(jsonb_build_object('slug', i.slug, 'nome', i.nome, 'por_dia', plataforma.materias_por_dia(i.plano, i.materias_dia),
        'recebidas', (SELECT count(*) FROM plataforma.materias m WHERE m.entregue_a = i.slug),
        'ultima', (SELECT max(publicar_em) FROM plataforma.materias m WHERE m.entregue_a = i.slug)) ORDER BY i.id), '[]'::jsonb)
      FROM plataforma.imobiliarias i WHERE i.situacao = 'ativa'),
    'ultimas', (SELECT coalesce(jsonb_agg(u ORDER BY u.publicar_em DESC), '[]'::jsonb) FROM (
      SELECT m.titulo, m.tipo, m.slug, m.publicar_em, i.nome imobiliaria FROM plataforma.materias m JOIN plataforma.imobiliarias i ON i.slug = m.entregue_a
      ORDER BY m.publicar_em DESC LIMIT 20) u),
    'temas', (SELECT coalesce(jsonb_agg(jsonb_build_object('tema', tema, 'titulo', titulo, 'tipo', tipo, 'slug', slug) ORDER BY id), '[]'::jsonb) FROM plataforma.materias)
  )
$f$;

REVOKE ALL ON FUNCTION plataforma.entregar_materias(date), plataforma.banco_situacao() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION plataforma.entregar_materias(date), plataforma.banco_situacao() TO plataforma_app;

-- Rotina (pg_cron, horário UTC; Campinas = UTC-3):
--   20h30 e 4h30 · POST https://corretordofuturo.app/banco-ciclo (traz as prontas do ramo e entrega hoje/amanhã)
--   5h00          · entrega direto no banco, de reserva (se o site não respondeu, entrega o que já está no banco)
-- O token fica em plataforma.config ('banco_ciclo_token'), gerado no banco; o site compara com o cabeçalho x-banco-ciclo.
INSERT INTO plataforma.config(chave, valor) VALUES ('banco_ciclo_token', encode(extensions.gen_random_bytes(24), 'hex')) ON CONFLICT (chave) DO NOTHING;
SELECT cron.schedule('plataforma-banco-ciclo', '30 7,23 * * *', $c$
  SELECT net.http_post(url := 'https://corretordofuturo.app/banco-ciclo',
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-banco-ciclo', (SELECT valor FROM plataforma.config WHERE chave = 'banco_ciclo_token')),
    body := '{}'::jsonb, timeout_milliseconds := 60000)
$c$);
SELECT cron.schedule('plataforma-banco-entrega', '0 8 * * *', $c$ SELECT plataforma.entregar_materias() $c$);
