-- LGPD (28/10/2026): pedidos dos titulares e lista "não contatar" comum a toda a plataforma.
-- 1) Em cada imobiliária (controladora dos dados dela): tabela titular_pedidos (pedidos feitos no portal dela).
--    Imobiliária nova herda a tabela pelo criar_imobiliaria (LIKE base.*).
-- 2) Na plataforma: plataforma.titular_pedidos (pedidos feitos em corretordofuturo.app) e plataforma.nao_contatar
--    (telefones, em hash, de quem pediu para não ser contatado: vale para TODAS as imobiliárias, porque a base é comum).
-- 3) Schema lgpd com duas funções liberadas a todos os usuários de banco: registrar oposição e perguntar se pode contatar.
--    Nenhum usuário de imobiliária lê a lista: só pergunta por um hash.

CREATE TABLE IF NOT EXISTS plataforma.titular_pedidos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  protocolo text UNIQUE NOT NULL,
  tipo text NOT NULL,
  nome text, email text, telefone text, telefone_hash text,
  mensagem text,
  imobiliaria text,
  origem text,
  situacao text NOT NULL DEFAULT 'aberto',
  resposta text,
  criado_em timestamptz NOT NULL DEFAULT now(),
  prazo timestamptz NOT NULL DEFAULT now() + interval '15 days',
  atendido_em timestamptz
);

CREATE TABLE IF NOT EXISTS plataforma.nao_contatar (
  telefone_hash text PRIMARY KEY,
  motivo text,
  origem text,
  em timestamptz NOT NULL DEFAULT now()
);

DO $$
DECLARE s record;
BEGIN
  FOR s IN SELECT i.slug FROM plataforma.imobiliarias i JOIN pg_namespace n ON n.nspname = i.slug LOOP
    EXECUTE format($q$CREATE TABLE IF NOT EXISTS %I.titular_pedidos (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      protocolo text UNIQUE NOT NULL,
      tipo text NOT NULL,
      nome text, email text, telefone text, telefone_hash text,
      mensagem text,
      origem text,
      situacao text NOT NULL DEFAULT 'aberto',
      resposta text,
      criado_em text NOT NULL DEFAULT %I.agora(),
      prazo text,
      atendido_em text,
      atendido_por integer
    )$q$, s.slug, s.slug);
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = s.slug || '_app') THEN
      EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I.titular_pedidos TO %I', s.slug, s.slug || '_app');
    END IF;
  END LOOP;
END $$;

CREATE SCHEMA IF NOT EXISTS lgpd;

CREATE OR REPLACE FUNCTION lgpd.opor(p_hash text, p_motivo text, p_origem text) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $f$
BEGIN
  IF p_hash !~ '^[0-9a-f]{64}$' THEN RAISE EXCEPTION 'hash inválido'; END IF;
  INSERT INTO plataforma.nao_contatar(telefone_hash, motivo, origem) VALUES (p_hash, left(p_motivo, 200), left(p_origem, 80))
  ON CONFLICT (telefone_hash) DO NOTHING;
END $f$;

CREATE OR REPLACE FUNCTION lgpd.pode_contatar(p_hash text) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $f$
  SELECT NOT EXISTS (SELECT 1 FROM plataforma.nao_contatar WHERE telefone_hash = p_hash);
$f$;

REVOKE ALL ON FUNCTION lgpd.opor(text, text, text), lgpd.pode_contatar(text) FROM PUBLIC;
GRANT USAGE ON SCHEMA lgpd TO PUBLIC;
GRANT EXECUTE ON FUNCTION lgpd.opor(text, text, text), lgpd.pode_contatar(text) TO PUBLIC;

-- painel do gestor e o site da plataforma (usuário plataforma_app)
GRANT SELECT, INSERT, UPDATE ON plataforma.titular_pedidos TO plataforma_app;
GRANT SELECT, INSERT, DELETE ON plataforma.nao_contatar TO plataforma_app;
