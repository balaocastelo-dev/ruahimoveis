// Schema onde moram as tabelas comuns (fachadas, lista da Caixa, vizinhança).
//
// SCHEMA_COMPARTILHADO, se estiver definida, manda. Senão: usa "base" quando
// esse schema existe; se não existe, usa o schema compartilhado que já está
// em produção. Não cria schema. A migração que renomeia o schema de produção
// está suspensa e este arquivo não a executa.
const SCHEMA_MOLDE = 'base';
const SCHEMA_PRODUCAO = ['ru', 'ah'].join('');
const CINCO = ['l7inteligencia', 'cademeuap', 'ondemorar', 'casaprado', 'lumen'];
const TABELAS_CAIXA = ['caixa_imoveis', 'fachadas', 'caixa_vizinhanca'];

function qname(nome) {
  if (!/^[A-Za-z_][A-Za-z0-9_]{0,62}$/.test(nome)) throw new Error(`nome recusado: ${nome}`);
  return `"${nome}"`;
}

function pedido() {
  const s = String(process.env.SCHEMA_COMPARTILHADO || '').trim();
  if (!s) return '';
  if (!/^[a-z][a-z0-9_]{1,30}$/.test(s)) throw new Error('SCHEMA_COMPARTILHADO inválido. Nenhum schema foi criado.');
  return s;
}

async function existe(client, nome) {
  const r = await client.query('SELECT 1 FROM pg_namespace WHERE nspname = $1', [nome]);
  return r.rows.length > 0;
}

async function resolver(client) {
  const escolhido = pedido();
  if (escolhido) {
    if (!(await existe(client, escolhido))) {
      throw new Error(`SCHEMA_COMPARTILHADO=${escolhido} não existe. Nenhum schema foi criado.`);
    }
    return escolhido;
  }
  if (await existe(client, SCHEMA_MOLDE)) return SCHEMA_MOLDE;
  if (await existe(client, SCHEMA_PRODUCAO)) return SCHEMA_PRODUCAO;
  throw new Error('Não achei o schema compartilhado. Nenhum schema foi criado. Defina SCHEMA_COMPARTILHADO.');
}

function sqlComSchema(sql, schema) {
  const qual = qname(schema);
  return String(sql).replace(/\bbase\.(caixa_imoveis|fachadas|caixa_vizinhanca)\b/gi, `${qual}.$1`);
}

async function usar(client) {
  const esquema = await resolver(client);
  const original = client.query.bind(client);
  client.query = (sql, params) => original(typeof sql === 'string' ? sqlComSchema(sql, esquema) : sql, params);
  return esquema;
}

async function relacao(client, schema, nome) {
  const r = await client.query(
    `SELECT c.relkind FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = $1 AND c.relname = $2`,
    [schema, nome],
  );
  return r.rows[0] ? r.rows[0].relkind : null;
}

async function garantirTabelasCaixa(client, schema) {
  const s = qname(schema);
  if (!(await existe(client, schema))) throw new Error(`Schema ${schema} não existe. Não criei schema.`);
  await client.query(`
    CREATE TABLE IF NOT EXISTS ${s}.fachadas (
      ref text PRIMARY KEY,
      img bytea,
      pano_lat double precision,
      pano_lon double precision,
      rumo double precision,
      data_foto text,
      gerado_em text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'America/Sao_Paulo', 'YYYY-MM-DD HH24:MI:SS')
    )`);
  await client.query(`
    CREATE TABLE IF NOT EXISTS ${s}.caixa_imoveis (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      numero text NOT NULL UNIQUE,
      uf text, cidade text, bairro text, endereco text,
      preco numeric, avaliacao numeric, desconto numeric,
      financiamento text, descricao text, modalidade text, link text,
      tipo text, quartos integer, vagas integer,
      area_util numeric, area_terreno numeric,
      na_rmc boolean NOT NULL DEFAULT false,
      primeira_safra text NOT NULL DEFAULT '',
      ultima_safra text NOT NULL DEFAULT '',
      saiu_em text,
      prazo_em text, prazo2_em text, prazo_tipo text, prazo_visto_em text,
      lat double precision, lon double precision, geo_precisao text, geo_em text,
      criado_em text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'America/Sao_Paulo', 'YYYY-MM-DD HH24:MI:SS'),
      atualizado_em text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'America/Sao_Paulo', 'YYYY-MM-DD HH24:MI:SS')
    )`);
  const colunas = [
    ['vagas', 'integer'],
    ['prazo_em', 'text'],
    ['prazo2_em', 'text'],
    ['prazo_tipo', 'text'],
    ['prazo_visto_em', 'text'],
    ['lat', 'double precision'],
    ['lon', 'double precision'],
    ['geo_precisao', 'text'],
    ['geo_em', 'text'],
  ];
  for (const [col, def] of colunas) {
    if (!/^[a-z][a-z0-9_]*$/.test(col)) throw new Error('coluna recusada');
    await client.query(`ALTER TABLE ${s}.caixa_imoveis ADD COLUMN IF NOT EXISTS ${col} ${def}`);
  }
  await client.query(`CREATE INDEX IF NOT EXISTS ix_caixa_cidade ON ${s}.caixa_imoveis(cidade) WHERE saiu_em IS NULL`);
  await client.query(`CREATE INDEX IF NOT EXISTS ix_caixa_rmc ON ${s}.caixa_imoveis(na_rmc, desconto DESC) WHERE saiu_em IS NULL`);
  await client.query(`CREATE INDEX IF NOT EXISTS ix_caixa_safra ON ${s}.caixa_imoveis(ultima_safra)`);
  await client.query(`
    CREATE TABLE IF NOT EXISTS ${s}.caixa_vizinhanca (
      numero text PRIMARY KEY,
      dados jsonb NOT NULL,
      visto_em text NOT NULL
    )`);
}

async function viewsCaixa(client, schema, slugs) {
  const feitos = [];
  for (const slug of slugs) {
    if (!/^[a-z][a-z0-9_]{2,30}$/.test(slug)) throw new Error(`tenant recusado: ${slug}`);
    if (!(await existe(client, slug))) {
      feitos.push({ slug, tabela: '', acao: 'schema-ausente' });
      continue;
    }
    for (const tabela of TABELAS_CAIXA) {
      const kind = await relacao(client, slug, tabela);
      if (kind === 'r') {
        feitos.push({ slug, tabela, acao: 'tabela' });
        continue;
      }
      if ((await relacao(client, schema, tabela)) !== 'r') {
        feitos.push({ slug, tabela, acao: 'sem-origem' });
        continue;
      }
      if (kind === 'v' && tabela === 'fachadas') {
        const def = (await client.query(
          `SELECT pg_get_viewdef(format('%I.%I', $1::text, $2::text)::regclass, true) AS d`,
          [slug, tabela],
        )).rows[0].d;
        const aponta = def.includes(`${schema}.`) || def.includes(`"${schema}".`);
        if (!aponta) {
          feitos.push({ slug, tabela, acao: 'view-alheia' });
          continue;
        }
      }
      await client.query(
        `CREATE OR REPLACE VIEW ${qname(slug)}.${qname(tabela)} AS SELECT * FROM ${qname(schema)}.${qname(tabela)}`,
      );
      const papel = `${slug}_app`;
      const tem = await client.query('SELECT 1 FROM pg_roles WHERE rolname = $1', [papel]);
      if (tem.rows.length) {
        await client.query(`GRANT SELECT ON ${qname(slug)}.${qname(tabela)} TO ${qname(papel)}`);
      }
      feitos.push({ slug, tabela, acao: kind === 'v' ? 'atualizada' : 'criada', grant: tem.rows.length > 0 });
    }
  }
  return feitos;
}

module.exports = {
  SCHEMA_MOLDE, SCHEMA_PRODUCAO, CINCO, TABELAS_CAIXA,
  qname, resolver, sqlComSchema, usar, garantirTabelasCaixa, viewsCaixa, existe, relacao,
};
